/**
 * Multi-entry Vite HTML Build Compatible htaccess for cPanel/Apache Hosting
 * 
 * This fixes the critical routing bug where router.php was redirecting ALL requests to enviar.php,
 * breaking the 5 independent HTML files (main/educacion/habilidades/contacto/servicios).
 * 
 * Solution: Check if requested file exists FIRST before PHP routing.
 */

function generateHTAccess() {
  return `# =============================================================================
# Vite Multi-Entry Build Compatible htaccess for Apache/cPanel Hosting
# =============================================================================
# Generated by: node scripts/fix-cpanel-routing.js [cPanel-path]
# Problem Fixed: router.php was redirecting ALL requests to enviar.php, breaking multi-entry HTML builds.
# Solution Strategy: Serve static files directly if they exist, only fallback to PHP routing for missing routes.

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /frontend/
</IfModule>

# =============================================================================
# PHASE 1: SERVE STATIC FILES DIRECT (CRITICAL FOR MULTI-ENTRY HTML BUILDS)
# =============================================================================

# List of Vite multi-entry build files that must be served directly
ViteMultiEntryFiles: main.html educacion.html habilidades.html contacto.html servicios.html
SetEnvIf Request_URI \.(main$|educacion$|habilidades$|contacto$|servicios$) vite-static-file

# Rule 1: If requested file exists in filesystem, serve it directly (NO PHP routing)
RewriteCond %{REQUEST_FILENAME} -f [OR]
RewriteCond %{REQUEST_FILENAME} -d
RewriteRule ^ - [L]

# Rule 2: For missing routes only, check if we need SPA fallback
# This prevents router.php from being called for static files that exist
RewriteCond %{HTTP:vite-static-file} !^1$ [NC,OR]
# Catch-all: Only use PHP routing if file/directory doesn't exist AND it's not already handled above  
RewriteRule ^([^.]+\.html)$ enviar.php?route=legacy-html-page [L,QSA]

# =============================================================================
# PHASE 2: API ROUTES (BACKEND ENDPOINTS - NO CHANGES FROM ORIGINAL)
# =============================================================================

# Backend API endpoints go through router.php with specific routing logic
RewriteCond %{REQUEST_URI} ^/(backend/api|api/) [NC]
RewriteRule ^(.*)$ enviar.php?route=api-request&path=$1 [L,QSA]

# Health check endpoint
RewriteRule ^health(/.*)?$ enviar.php?route=health-check [L,QSA]

# Legacy form submissions
RewriteRule ^enviar\.php(/.*)? envio\.php [L]

# =============================================================================
# PHASE 3: SPA FALLBACK (ONLY FOR DYNAMIC ROUTES THAT DON'T EXIST)
# =============================================================================

# Catch-all for routes that don't exist as files/directories
# Cloudflare proxies may add .html extensions dynamically
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{REQUEST_FILENAME} !-d
RewriteRule ^(.*)$ enviar.php?_fallback=%{REQUEST_URI} [L,QSA]

# =============================================================================
# SECURITY: Prevent directory traversal and other attacks
# =============================================================================

<IfModule mod_rewrite.c>
  RewriteEngine On
  
  # Prevent access to sensitive files
  <FilesMatch "\\.(env|ini|conf)$">
    Order allow,deny
    Deny from all
  </FilesMatch>
  
  # Protect .htaccess itself from direct manipulation  
  RenameHTAccess .htaccess
</IfModule>

# =============================================================================
# CLOUDFLARE COMPATIBILITY (PROXY CACHE DIRECTIVES)
# =============================================================================

# Tell Cloudflare these are static files 
Header set X-Content-Type-Options nosniff
Header set X-Frame-Options SAMEORIGIN
<IfModule mod_headers.c>
  # Cache static HTML files for better CDN performance
  AddCacheControl "public, max-age=3600" types="text/html; charset=utf-8"
</IfModule>`;
}

// ============================================================================
// FTP UPLOAD UTILITY
// ============================================================================

class FtpUploader {
  async uploadFile(fileContent, remotePath) {
    const client = new ftp.Client();
    client.ftp.verbose = false;
    
    try {
      console.log(`📡 Connecting to FTP: ${config.host}`);
      await client.access({
        host: config.host,
        user: config.user || "anonymous",
        password: config.password || "",
        secure: config.secure,
      });

      const remoteDir = normalizeRemoteDir(config.targetDir, "/public_html");
      console.log(`📂 Target directory: ${remoteDir}`);
      
      // Create directories if needed
      await client.ensureDir(remoteDir + "/htaccess.txt");
      await client.cd(`${remoteDir}/htaccess.txt`);

      // Upload .htaccess as text file
      await client.put(config.rawBuffer || Buffer.from(fileContent, "utf-8"), ".htaccess");
      console.log(`✅ Uploaded .htaccess to: ${remoteDir}/.htaccess`);
      
      // Also copy to dist root for easy access (backup)
      const backupPath = `${remoteDir}/.htaccess.backup`;
      await client.put(Buffer.from(fileContent, "utf-8"), backupPath);
      console.log(`💾 Backup uploaded to: ${backupPath}`);

    } catch (err) {
      console.error(`❌ Error uploading .htaccess:`, err.message);
      throw err;
    } finally {
      client.close();
    }
  }

  static uploadHTAccess() {
    const content = generateHTAccess();
    return new FtpUploader().uploadFile(content, ".htaccess");
  }
}

// ============================================================================
// HELPERS
// ============================================================================

function normalizeRemoteDir(value, fallback) {
  const raw = (value || "").trim().replace(/^["']|["']$/g, "");
  if (!raw) return fallback;
  return raw.startsWith("/") ? raw : `/${raw}`;
}

